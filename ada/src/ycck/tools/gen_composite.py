#!/usr/bin/env python3
"""Generates wuffs-base-pixel_composite.ads / .adb: four of the eight
wuffs_private_impl__composite_* helpers of upstream's
internal/cgen/base/pixconv-submodule-regular.c, as public functions.

    python3 gen_composite.py [path/to/wuffs checkout] [output directory]
    python3 gen_composite.py --check

--check fails if the checked-in files are not exactly this script's
output, or if any of the generated function bodies is not found, character
for character, in ada/src/pixel/wuffs-base-pixel_rows.adb (the other
generated copy).

The same functions exist, translated by the same translator
(ada/src/pixel/tools/gen_rows.py, which this script imports), as local
functions in the body of Wuffs.Base.Pixel_Rows.  That package is frozen
and does not export them; the YCCK swizzler needs four of them for
compositing onto a pixel buffer.  TO RELOCATE: once src/pixel can change,
export them from there and delete this package.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "pixel", "tools"))
import gen_rows  # noqa: E402


# The helpers that the YCCK code calls (compositing a non-premultiplied
# source); upstream's other four (a premultiplied source) are not generated.
USED = ("composite_nonpremul_nonpremul_u32_axxx",
        "composite_nonpremul_nonpremul_u64_axxx",
        "composite_premul_nonpremul_u32_axxx",
        "composite_premul_nonpremul_u64_axxx")


def generate(wuffs):
    cfile = os.path.join(wuffs, "internal", "cgen", "base",
                         "pixconv-submodule-regular.c")
    text = "\n" + gen_rows.strip_comments(open(cfile, encoding="utf-8").read())
    comps = list(gen_rows.functions(text, "composite_", r"uint(?:32|64)_t"))
    for n, p, b in comps:
        typ = "u64" if "_u64_" in n else "u32"
        gen_rows.COMPOSITES[n] = (
            gen_rows.ada_name(n.replace("wuffs_private_impl__", "")),
            [typ, typ], typ)
    head = ["--  GENERATED by src/ycck/tools/gen_composite.py from upstream Wuffs'",
            "--  internal/cgen/base/pixconv-submodule-regular.c.  Do not edit.",
            "--"]
    ads = head + [
        "--  Compositing one pixel over another (the SRC_OVER blend).  C:",
        "--  wuffs_private_impl__composite_<dst>_<src>_u32_axxx / _u64_axxx: Dst and",
        "--  Src are 0xAARRGGBB (U32, 8 bits per channel) or 0xAAAARRRRGGGGBBBB",
        "--  (U64, 16 bits per channel) colours, each premultiplied or not as the",
        "--  name says, and the result is in Dst's form.  Plain numbers in, a",
        "--  number out; no arrays.",
        "--",
        "--  TO RELOCATE: the body of Wuffs.Base.Pixel_Rows (frozen) has the same",
        "--  functions, not exported.  See tools/gen_composite.py.",
        "",
        "package Wuffs.Base.Pixel_Composite with Pure, SPARK_Mode is",
        ""]
    adb = head[:2] + [
        "",
        "package body Wuffs.Base.Pixel_Composite with SPARK_Mode is",
        "",
        "   pragma Assertion_Policy (Ignore);",
        "",
        "   use Interfaces;",
        ""]
    for n, p, b in comps:
        if not any(n.endswith(u) for u in USED):
            continue
        sig, out = gen_rows.translate_composite(n, p, b)
        ads += ["   --  C: %s." % n, sig[0], sig[1] + ";", ""]
        adb += out
    ads.append("end Wuffs.Base.Pixel_Composite;")
    adb.append("end Wuffs.Base.Pixel_Composite;")
    return "\n".join(ads) + "\n", "\n".join(adb) + "\n"


def same_as_pixel_rows(adb):
    """True if every function body of the generated package body occurs,
    character for character, in the body of Wuffs.Base.Pixel_Rows (which
    has them as local functions): the two copies differ only in the package
    around them."""
    rows = open(os.path.join(HERE, "..", "..", "pixel",
                             "wuffs-base-pixel_rows.adb")).read()
    funcs = [m.group(0) for m in
             re.finditer(r"^   function (\w+)\n.*?^   end \1;\n", adb, re.M | re.S)]
    ok = len(funcs) == len(USED)
    for f in funcs:
        if f not in rows:
            print("not found unchanged in wuffs-base-pixel_rows.adb:")
            print(f.split("\n")[0])
            ok = False
    return ok


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    wuffs = args[0] if args else os.path.join(HERE, "..", "..", "..", "..", "wuffs")
    outdir = args[1] if len(args) > 1 else os.path.join(HERE, "..")
    ads, adb = generate(wuffs)
    ok = True
    for name, text in (("wuffs-base-pixel_composite.ads", ads),
                       ("wuffs-base-pixel_composite.adb", adb)):
        path = os.path.join(outdir, name)
        if "--check" in sys.argv:
            if not os.path.exists(path) or open(path).read() != text:
                print("%s is not the generator's output" % path)
                ok = False
        else:
            open(path, "w").write(text)
    if "--check" in sys.argv and not same_as_pixel_rows(adb):
        ok = False
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
