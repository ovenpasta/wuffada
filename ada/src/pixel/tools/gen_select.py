#!/usr/bin/env python3
"""Generates wuffs-base-pixel_select.ads: which row function upstream's
wuffs_base__pixel_swizzler__prepare chooses for each (source format,
destination format, blend).

    python3 gen_select.py [path/to/wuffs checkout] [output directory]
    python3 gen_select.py --check

The table is not transcribed from the C switch statements; it is observed.
This script writes a small C program around upstream's release C file
(wuffs/release/c/wuffs-unsupported-snapshot.c, compiled with
WUFFS_CONFIG__AVOID_CPU_ARCH so that only the scalar row functions exist),
which calls prepare for every pair of the pixel formats that have a whole
number of bytes per pixel and for blend 0 (SRC), 1 (SRC_OVER) and 2 (not a
blend), with 1024 byte palettes, and prints the name of the function that
the swizzler's function pointer ends up equal to.  Needs a C compiler (cc).

What prepare does to the destination palette for an indexed source, and
how it reacts to palettes shorter than 1024 bytes, is not part of this
table; that is written by hand in wuffs-base-pixel_swizzler.adb and tested
against the C by the oracle (ada/tests_pixel/oracle).
"""

import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_rows  # noqa: E402

FORMATS = [
    "A", "Y", "Y_16LE", "Y_16BE", "YA_Nonpremul", "YA_Premul", "YXXX",
    "Indexed_BGRA_Nonpremul", "Indexed_BGRA_Premul", "Indexed_BGRA_Binary",
    "BGR_565", "BGR", "BGRA_Nonpremul", "BGRA_Nonpremul_4x16LE",
    "BGRA_Premul", "BGRA_Premul_4x16LE", "BGRA_Binary", "BGRX", "RGB",
    "RGBA_Nonpremul", "RGBA_Nonpremul_4x16LE", "RGBA_Premul",
    "RGBA_Premul_4x16LE", "RGBA_Binary", "RGBX",
]


def c_format(name):
    return "WUFFS_BASE__PIXEL_FORMAT__" + name.upper().replace(
        "INDEXED_", "INDEXED__")


C_TEMPLATE = r"""
#define WUFFS_IMPLEMENTATION
#define WUFFS_CONFIG__AVOID_CPU_ARCH
#define WUFFS_CONFIG__MODULES
#define WUFFS_CONFIG__MODULE__BASE
#define WUFFS_CONFIG__MODULE__BASE__CORE
#define WUFFS_CONFIG__MODULE__BASE__PIXCONV
#include "%(cfile)s"
#include <stdio.h>
static const struct { const char* name; wuffs_base__pixel_swizzler__func f; } funcs[] = {
%(funcs)s
};
static const uint32_t formats[] = {
%(formats)s
};
int main(void) {
  size_t nf = sizeof(formats) / sizeof(formats[0]);
  for (size_t s = 0; s < nf; s++) {
    for (size_t d = 0; d < nf; d++) {
      for (int blend = 0; blend < 3; blend++) {
        uint8_t dp[1024] = {0};
        uint8_t sp[1024] = {0};
        wuffs_base__pixel_swizzler p;
        wuffs_base__pixel_swizzler__prepare(
            &p, wuffs_base__make_pixel_format(formats[d]),
            wuffs_base__make_slice_u8(dp, 1024),
            wuffs_base__make_pixel_format(formats[s]),
            wuffs_base__make_slice_u8(sp, 1024), (wuffs_base__pixel_blend)blend);
        const char* name = "-";
        if (p.private_impl.func) {
          name = "?";
          for (size_t k = 0; k < sizeof(funcs) / sizeof(funcs[0]); k++) {
            if (funcs[k].f == p.private_impl.func) {
              name = funcs[k].name;
            }
          }
        }
        printf("%%zu %%zu %%d %%s\n", s, d, blend, name);
      }
    }
  }
  return 0;
}
"""


def observe(wuffs):
    pix = os.path.join(wuffs, "internal", "cgen", "base",
                       "pixconv-submodule-regular.c")
    text = "\n" + gen_rows.strip_comments(open(pix, encoding="utf-8").read())
    names = []
    for n, p, b in gen_rows.functions(text, "swizzle_", r"uint64_t"):
        if "x86" in n or "transparent_black" in n or "squash" in n:
            continue
        names.append(n)
    snapshot = os.path.abspath(os.path.join(
        wuffs, "release", "c", "wuffs-unsupported-snapshot.c"))
    src = C_TEMPLATE % {
        "cfile": snapshot,
        "funcs": "\n".join('  {"%s", &%s},' % (gen_rows.row_ada_name(n), n)
                           for n in names),
        "formats": "\n".join("  %s," % c_format(f) for f in FORMATS),
    }
    with tempfile.TemporaryDirectory() as tmp:
        cpath = os.path.join(tmp, "dump.c")
        open(cpath, "w").write(src)
        exe = os.path.join(tmp, "dump")
        subprocess.run(["cc", "-std=c99", "-O1", "-w", "-o", exe, cpath],
                       check=True)
        out = subprocess.run([exe], check=True, capture_output=True,
                             text=True).stdout
    table = {}
    for line in out.splitlines():
        s, d, blend, name = line.split()
        if name == "?":
            sys.exit("prepare chose a function this script does not know")
        table[(int(s), int(d), int(blend))] = name
    return table


def generate(wuffs):
    table = observe(wuffs)
    o = []
    A = o.append
    A("--  GENERATED by tools/gen_select.py by observing upstream Wuffs'")
    A("--  wuffs_base__pixel_swizzler__prepare (scalar build).  Do not edit;")
    A("--  run the generator again.")
    A("--")
    A("--  Which row function the swizzler uses for a source format, a")
    A("--  destination format and a blend.  Blend is 0 for SRC, 1 for")
    A("--  SRC_OVER; any other value is passed as 2 (C then still accepts")
    A("--  the conversions that do not depend on the blend).  Found is False")
    A("--  where C's prepare ends with a null function pointer.")
    A("--")
    A("--  For an indexed source the answer assumes that the palettes are")
    A("--  long enough; Wuffs.Base.Pixel_Swizzler.Prepare checks that.")
    A("")
    A("with Wuffs.Base.Pixel_Formats;")
    A("with Wuffs.Base.Pixel_Rows;")
    A("")
    A("package Wuffs.Base.Pixel_Select with Pure, SPARK_Mode is")
    A("")
    A("   use Wuffs.Base.Pixel_Formats;")
    A("   use Wuffs.Base.Pixel_Rows;")
    A("")
    A("   subtype Blend_Class is U8 range 0 .. 2;")
    A("")
    A("   type Selection is record")
    A("      Found : Boolean      := False;")
    A("      Fn    : Row_Function := Row_Function'First;")
    A("   end record;")
    A("")
    A("   None : constant Selection := (Found => False, Fn => Row_Function'First);")
    A("")
    nf = len(FORMATS)
    varies = {}
    for s in range(nf):
        if all(table[(s, d, b)] == "-" for d in range(nf) for b in range(3)):
            continue
        varies[s] = any(len({table[(s, d, b)] for b in range(3)}) > 1
                        for d in range(nf))
        A("   function From_%s (Dst : U32%s) return Selection is"
          % (FORMATS[s], "; Blend : Blend_Class" if varies[s] else ""))
        A("     (case Dst is")
        for d in range(nf):
            names = [table[(s, d, b)] for b in range(3)]
            if names == ["-"] * 3:
                continue
            A("        when Repr_%s =>" % FORMATS[d])
            if names[0] == names[1] == names[2]:
                A("           (True, Fn_%s)," % names[0])
            else:
                A("           (case Blend is")
                for b in range(3):
                    val = ("None" if names[b] == "-"
                           else "(True, Fn_%s)" % names[b])
                    A("              when %d => %s%s" % (b, val,
                                                         "," if b < 2 else "),"))
        A("        when others => None);")
        A("")
    A("   function Select_Row_Function")
    A("     (Src, Dst : U32; Blend : Blend_Class) return Selection")
    A("   is")
    A("     (case Src is")
    for s in range(nf):
        if all(table[(s, d, b)] == "-" for d in range(nf) for b in range(3)):
            continue
        A("        when Repr_%s => From_%s (Dst%s),"
          % (FORMATS[s], FORMATS[s], ", Blend" if varies[s] else ""))
    A("        when others => None);")
    A("")
    A("end Wuffs.Base.Pixel_Select;")
    return "\n".join(o) + "\n"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    wuffs = args[0] if args else os.path.join(HERE, "..", "..", "..", "..", "wuffs")
    outdir = args[1] if len(args) > 1 else os.path.join(HERE, "..")
    text = generate(wuffs)
    path = os.path.join(outdir, "wuffs-base-pixel_select.ads")
    if "--check" in sys.argv:
        if not os.path.exists(path) or open(path).read() != text:
            sys.exit("%s is not the generator's output" % path)
    else:
        open(path, "w").write(text)


if __name__ == "__main__":
    main()
