#!/bin/sh
# Regenerates ../base_oracle_data.ads from upstream Wuffs' C base library:
#  - the expected digest of every sweep in oracle.c, and
#  - the base status messages, read from the release C file.
# Usage: ./regen.sh [path/to/wuffs checkout]   (default: ../../../wuffs)
set -eu
here=$(cd "$(dirname "$0")" && pwd)
wuffs=${1:-$here/../../../wuffs}
cfile=$wuffs/release/c/wuffs-unsupported-snapshot.c
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cc -std=c99 -O1 -Wall -Wno-unused-function -Wno-attributes -fsanitize=address,undefined \
  -fno-sanitize-recover=all -DWUFFS_C_FILE="\"$cfile\"" -o "$tmp/oracle" "$here/oracle.c"
"$tmp/oracle" > "$tmp/digests.txt"
python3 "$here/statuses.py" "$cfile" > "$tmp/statuses.txt"
order=$(printf '\001\000' | od -An -tx2 | tr -d ' ')
{
  echo "--  Generated by oracle/regen.sh from upstream Wuffs' C base library."
  echo "--  Do not edit.  See oracle/oracle.c for what each digest covers."
  echo
  echo "with Wuffs.Base;"
  echo
  echo "package Base_Oracle_Data is"
  echo
  echo "   --  Byte order of the machine that ran the oracle; Slices_Bulk is"
  echo "   --  only comparable on a machine with the same order."
  if [ "$order" = "0001" ]; then
    echo "   Oracle_Is_Little_Endian : constant Boolean := True;"
  else
    echo "   Oracle_Is_Little_Endian : constant Boolean := False;"
  fi
  echo
  cat "$tmp/digests.txt"
  echo
  cat "$tmp/statuses.txt"
  echo
  echo "end Base_Oracle_Data;"
} > "$here/../base_oracle_data.ads"
echo "wrote $here/../base_oracle_data.ads"
