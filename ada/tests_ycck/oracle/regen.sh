#!/bin/sh
# Regenerates ../ycck_oracle_data.ads from upstream Wuffs' C base library:
# the expected digests of every sweep in oracle.c.
#
# The oracle is built four times, each time with ASan and UBSan:
#
#   gcc   scalar   WUFFS_CONFIG__AVOID_CPU_ARCH: the code the Ada port
#                  follows.  This build's output is what gets written.
#   gcc   simd     upstream's AVX2 bt601fr BGRX / RGBX converters are used
#                  (on a machine with AVX2).
#   clang scalar
#   clang simd     as gcc simd, and also upstream's AVX2 h2v2 triangle
#                  upsampler, which upstream compiles only under clang.
#
# All four outputs must be identical; if any differs this script prints
# the difference and fails without writing anything.  The digests cover the
# scratch buffer too, so "identical" includes what the upsamplers leave in
# it.
#
# Usage: ./regen.sh [path/to/wuffs checkout]   (default: ../../../wuffs)
# Environment: GCC (default gcc), CLANG (default clang).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
wuffs=${1:-$here/../../../wuffs}
cfile=$wuffs/release/c/wuffs-unsupported-snapshot.c
gcc=${GCC:-gcc}
clang=${CLANG:-clang}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
flags="-I$here -std=c99 -O2 -Wall -Wno-unused-function -Wno-attributes -fsanitize=address,undefined -fno-sanitize-recover=all"
for cc in "$gcc" "$clang"; do
  name=$(basename "$cc")
  "$cc" $flags -DWUFFS_CONFIG__AVOID_CPU_ARCH -DWUFFS_C_FILE="\"$cfile\"" -o "$tmp/$name-scalar" "$here/oracle.c"
  "$cc" $flags -DWUFFS_C_FILE="\"$cfile\"" -o "$tmp/$name-simd" "$here/oracle.c"
  "$tmp/$name-scalar" > "$tmp/$name-scalar.txt"
  "$tmp/$name-simd" > "$tmp/$name-simd.txt"
done
ref=$tmp/$(basename "$gcc")-scalar.txt
status=0
for out in "$tmp"/*.txt; do
  if ! cmp -s "$ref" "$out"; then
    echo "$(basename "$out" .txt) disagrees with $(basename "$ref" .txt):" >&2
    diff "$ref" "$out" >&2 || true
    status=1
  fi
done
if [ $status -ne 0 ]; then
  exit 1
fi
{
  echo "--  Generated by oracle/regen.sh from upstream Wuffs' C base library"
  echo "--  (gcc scalar build; the gcc SIMD, clang scalar and clang SIMD builds"
  echo "--  printed the same).  Do not edit."
  echo "--  See oracle/oracle.c for what each digest covers."
  echo
  echo "with Wuffs;"
  echo
  echo "package YCCK_Oracle_Data is"
  echo
  echo "   --  The digest at each checkpoint of a sweep (oracle.c: mark)."
  echo "   type Mark_Array is array (Natural range <>) of Wuffs.U64;"
  echo
  cat "$ref"
  echo
  echo "end YCCK_Oracle_Data;"
} > "$here/../ycck_oracle_data.ads"
echo "wrote $here/../ycck_oracle_data.ads (gcc scalar, gcc simd, clang scalar, clang simd agree)"
