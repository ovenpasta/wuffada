#!/bin/sh
# Regenerates ../token_oracle_data.ads from upstream Wuffs' C: the expected
# digest of every sweep in oracle.c.
#
# The oracle is built twice, with gcc and with clang, each time with ASan
# and UBSan (any report is fatal).  Both outputs must be identical; if they
# differ this script prints the difference and fails without writing
# anything.  The gcc build's output is what gets written.
#
# Usage: ./regen.sh [path/to/wuffs checkout]   (default: ../../../wuffs)
# Environment: GCC (default gcc), CLANG (default clang).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
wuffs=${1:-$here/../../../wuffs}
cfile=$wuffs/release/c/wuffs-unsupported-snapshot.c
gcc=${GCC:-gcc}
clang=${CLANG:-clang}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
flags="-std=c99 -O2 -Wall -Wno-unused-function -Wno-attributes -fsanitize=address,undefined -fno-sanitize-recover=all"
for cc in "$gcc" "$clang"; do
  name=$(basename "$cc")
  "$cc" $flags -DWUFFS_C_FILE="\"$cfile\"" -o "$tmp/$name" "$here/oracle.c"
  "$tmp/$name" > "$tmp/$name.txt"
done
ref=$tmp/$(basename "$gcc").txt
other=$tmp/$(basename "$clang").txt
if ! cmp -s "$ref" "$other"; then
  echo "clang disagrees with gcc:" >&2
  diff "$ref" "$other" >&2 || true
  exit 1
fi
{
  echo "--  Generated by oracle/regen.sh from upstream Wuffs' C (gcc build, with"
  echo "--  ASan and UBSan; the clang build printed the same).  Do not edit."
  echo "--  See oracle/oracle.c for what each digest covers."
  echo
  echo "with Wuffs;"
  echo
  echo "package Token_Oracle_Data is"
  echo
  cat "$ref"
  echo
  echo "end Token_Oracle_Data;"
} > "$here/../token_oracle_data.ads"
echo "wrote $here/../token_oracle_data.ads (gcc and clang agree)"
