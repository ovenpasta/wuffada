#!/bin/sh
# Regenerates the wrapper tests of Wuffs.Runtime.X86.SSE42 and AVX2 from the
# one method table in gen.py (../x86_methods.ads, ../x86_methods.list,
# ../x86_test_cases.adb, x86_oracle.c), then builds the C oracle with gcc
# and with clang, runs both, fails if they disagree, and writes their
# digests to ../x86_oracle_data.ads (checked in, so that test_x86 needs no C
# compiler). Needs an x86-64 CPU with SSE4.2, PCLMUL, POPCNT and AVX2.
# Usage: ./regen.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
python3 "$here/gen.py"
flags="-std=c99 -O2 -Wall -Wextra -msse4.2 -mpclmul -mpopcnt -mavx2 -mbmi2"
gcc $flags -o "$tmp/oracle.gcc" "$here/x86_oracle.c"
"$tmp/oracle.gcc" > "$tmp/digests.gcc"
compilers=gcc
if command -v clang > /dev/null 2>&1; then
    clang $flags -o "$tmp/oracle.clang" "$here/x86_oracle.c"
    "$tmp/oracle.clang" > "$tmp/digests.clang"
    cmp "$tmp/digests.gcc" "$tmp/digests.clang" || { echo "regen.sh: gcc and clang disagree" >&2; exit 1; }
    compilers="gcc and clang"
fi
{
    echo "--  Part of wuffada (wuffs-ada: Wuffs to Ada)."
    echo "--  SPDX-License-""Identifier: Apache-2.0 OR MIT"
    echo
    echo "--  Generated by ada/tests/simd/oracle/regen.sh: the digests that"
    echo "--  oracle/x86_oracle.c prints (built with $compilers, which agree), the"
    echo "--  results of upstream's _mm_* intrinsics over test_x86's inputs.  Do"
    echo "--  not edit."
    echo
    echo "with Interfaces;"
    echo "with X86_Methods;"
    echo
    echo "package X86_Oracle_Data is"
    echo
    echo "   use X86_Methods;"
    echo
    echo "   type Digests is array (1 .. X86_Methods.Number_Of_Checkpoints) of Interfaces.Unsigned_64;"
    echo
    echo "   Expected : constant array (X86_Methods.Method) of Digests :="
    printf '     ['
    sed -e '1s/^      //' -e '$s/$/];/' "$tmp/digests.gcc"
    echo
    echo "end X86_Oracle_Data;"
} > "$here/../x86_oracle_data.ads"
echo "wrote $here/../x86_oracle_data.ads ($compilers)"
