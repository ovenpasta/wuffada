#!/bin/sh
# Regenerates ../pixel_oracle_data.ads from upstream Wuffs' C base library:
# the expected digest of every sweep in oracle.c.
#
# The oracle is built twice, both times with ASan and UBSan:
#   - with WUFFS_CONFIG__AVOID_CPU_ARCH: only the scalar row functions,
#     which are the ones the Ada port translates.  This build's output is
#     what gets written.
#   - without it: the row functions that have x86 SIMD variants use them
#     (on a machine that supports them).  Its output must be identical,
#     i.e. upstream's SIMD and scalar paths agree on every sweep; if not,
#     this script fails.
#
# Usage: ./regen.sh [path/to/wuffs checkout]   (default: ../../../wuffs)
set -eu
here=$(cd "$(dirname "$0")" && pwd)
wuffs=${1:-$here/../../../wuffs}
cfile=$wuffs/release/c/wuffs-unsupported-snapshot.c
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
flags="-I$here -std=c99 -O2 -Wall -Wno-unused-function -Wno-attributes -fsanitize=address,undefined -fno-sanitize-recover=all"
cc $flags -DWUFFS_CONFIG__AVOID_CPU_ARCH -DWUFFS_C_FILE="\"$cfile\"" -o "$tmp/scalar" "$here/oracle.c"
cc $flags -DWUFFS_C_FILE="\"$cfile\"" -o "$tmp/simd" "$here/oracle.c"
"$tmp/scalar" > "$tmp/scalar.txt"
"$tmp/simd" > "$tmp/simd.txt"
if ! cmp -s "$tmp/scalar.txt" "$tmp/simd.txt"; then
  echo "upstream's SIMD and scalar builds disagree:" >&2
  diff "$tmp/scalar.txt" "$tmp/simd.txt" >&2 || true
  exit 1
fi
{
  echo "--  Generated by oracle/regen.sh from upstream Wuffs' C base library"
  echo "--  (scalar build; the SIMD build printed the same).  Do not edit."
  echo "--  See oracle/oracle.c for what each digest covers."
  echo
  echo "with Wuffs;"
  echo
  echo "package Pixel_Oracle_Data is"
  echo
  echo "   --  The digest at each checkpoint of a sweep (oracle.c: mark)."
  echo "   type Mark_Array is array (Natural range <>) of Wuffs.U64;"
  echo
  cat "$tmp/scalar.txt"
  echo
  echo "end Pixel_Oracle_Data;"
} > "$here/../pixel_oracle_data.ads"
echo "wrote $here/../pixel_oracle_data.ads (SIMD build agrees)"
