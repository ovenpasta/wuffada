// Package adagen generates Ada code from (type- and bounds-checked) Wuffs
// ASTs. It is the Ada sibling of the Wuffs repository's internal/cgen
// package, which generates C code.
//
// Provenance: the meaning given to each AST node, and the shape of some
// lowerings (iterate loops, choose statements, the "magic" initialization
// check of public methods), follow internal/cgen at github.com/google/wuffs
// commit a87f0bb, which is Copyright 2017 The Wuffs Authors and licensed
// "Apache-2.0 OR MIT". No file here is a verbatim copy.
//
// Structure: analyze.go gathers the package-level declarations; lower.go
// turns each function's AST into the IR of ir.go; passes.go runs IR passes;
// emit.go prints IR; decls.go prints the package spec and body around the
// functions.
//
// The generator rejects, with an error, any construct that it does not
// handle. It never emits a placeholder.
package adagen

import (
	"fmt"
	"strings"

	a "github.com/google/wuffs/lang/ast"
	t "github.com/google/wuffs/lang/token"
)

// DefaultBasePackage is the Ada package that provides the base library's
// status constants and computational helpers to generated code.
const DefaultBasePackage = "Wuffs.Runtime.Temp_Base"

// Options configures Generate.
type Options struct {
	// PackageName is the Wuffs package name, such as "adler32".
	PackageName string

	// PackageID is the package's status-code namespace: see Wuffs.Status in
	// ada/src/root/wuffs.ads. It must be non-zero if the package declares
	// statuses.
	PackageID uint32

	// BasePackage overrides DefaultBasePackage.
	BasePackage string

	// SourceNames are the names of the source files, for the "generated
	// from" header. They default to the names recorded in the ASTs.
	SourceNames []string
}

// Output is a generated Ada package.
type Output struct {
	UnitName string // E.g. "Wuffs.Std.Adler32".
	SpecFile string // E.g. "wuffs-std-adler32.ads".
	BodyFile string // E.g. "wuffs-std-adler32.adb".
	Spec     []byte
	Body     []byte

	// Skipped lists the Wuffs functions that were not generated because they
	// need a cpu_arch (SIMD) capability.
	Skipped []string
}

// StdRootSpec is the source text of the parent package of every generated
// package, to be saved as StdRootFile.
const StdRootSpec = "" +
	"--  Code generated by wuffs-ada.  DO NOT EDIT.\n" +
	"--\n" +
	"--  The parent of the packages generated from Wuffs' standard library.\n" +
	"\n" +
	"package Wuffs.Std with Pure is\n" +
	"end Wuffs.Std;\n"

// StdRootFile is the file name for StdRootSpec.
const StdRootFile = "wuffs-std.ads"

type gen struct {
	tm    *t.Map
	files []*a.File
	opts  Options

	basePkg          string
	adaPkgSimpleName string // E.g. "Adler32".
	adaPkgName       string // E.g. "Wuffs.Std.Adler32".

	names      map[string]string // Lower-cased package-level Ada names.
	namedTypes map[string]*namedType

	structs    map[t.ID]*structInfo
	structList []*structInfo
	consts     map[t.ID]*constInfo
	constList  []*constInfo
	statuses   map[t.ID]*statusInfo
	statusList []*statusInfo
	funcs      map[t.QQID]*funcInfo
	funcList   []*funcInfo
	skipped    []string

	// useType records which modular types' operators the body uses.
	useType map[int]bool
}

// Generate generates the Ada package for the Wuffs package whose checked
// files are given.
func Generate(tm *t.Map, files []*a.File, opts Options) (*Output, error) {
	if opts.PackageName == "" || !isValidAdaIdent(mangleGlobal(opts.PackageName)) {
		return nil, fmt.Errorf("adagen: bad package name %q", opts.PackageName)
	}
	g := &gen{
		tm:               tm,
		files:            files,
		opts:             opts,
		basePkg:          opts.BasePackage,
		adaPkgSimpleName: mangleGlobal(opts.PackageName),
		names:            map[string]string{},
		namedTypes:       map[string]*namedType{},
		structs:          map[t.ID]*structInfo{},
		consts:           map[t.ID]*constInfo{},
		statuses:         map[t.ID]*statusInfo{},
		funcs:            map[t.QQID]*funcInfo{},
		useType:          map[int]bool{},
	}
	if g.basePkg == "" {
		g.basePkg = DefaultBasePackage
	}
	g.adaPkgName = "Wuffs.Std." + g.adaPkgSimpleName

	if err := g.analyze(); err != nil {
		return nil, fmt.Errorf("adagen: %v", err)
	}
	for _, fi := range g.funcList {
		if err := g.lowerFunc(fi); err != nil {
			filename, line := fi.ast.Filename(), fi.ast.Line()
			return nil, fmt.Errorf("adagen: func %s (at %s:%d): %v",
				fi.ast.QQID().Str(g.tm), filename, line, err)
		}
		countUses(fi.ir)
	}

	unit := strings.ToLower(strings.ReplaceAll(g.adaPkgName, ".", "-"))
	out := &Output{
		UnitName: g.adaPkgName,
		SpecFile: unit + ".ads",
		BodyFile: unit + ".adb",
		Skipped:  g.skipped,
	}
	spec := g.genSpec()
	body := g.genBody()
	out.Spec = []byte(g.header() + g.withClauses(spec, "") + spec)
	out.Body = []byte(g.header() + g.withClauses(body, spec) + body)
	return out, nil
}

// errNotYet makes the error for a construct that a later milestone will
// handle.
func errNotYet(format string, args ...interface{}) error {
	return fmt.Errorf("not yet supported: "+format, args...)
}
