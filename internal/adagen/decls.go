// This file prints the package spec and body: everything but the function
// bodies' statements.

func (g *gen) header() string {
	p := &printer{}
	p.comment(fmt.Sprintf("Code generated by wuffs-ada from the Wuffs package %q.  DO NOT EDIT.", g.opts.PackageName))
	p.comment("\nSources:")
	names := g.opts.SourceNames
	if len(names) == 0 {
		for _, f := range g.files {
			names = append(names, f.Filename())
		}
	}
	for _, s := range names {
		p.comment("  " + strings.ReplaceAll(s, "\\", "/"))
	}
	if len(g.skipped) > 0 {
		p.comment("\nNot generated, as they need a cpu_arch (SIMD) capability:")
		for _, s := range g.skipped {
			p.comment("  " + s)
		}
	}
	p.line("")
	return p.b.String()
}

// withClauses returns the context clause for a unit whose text is given.
// What it needs is found by scanning that text, so that there is exactly one
// place (the text itself) that decides what a unit depends on. A body does
// not repeat its spec's clauses.
func (g *gen) withClauses(text string, specText string) string {
	needs := func(s string, unit string) bool { return strings.Contains(s, unit+".") }
	candidates := []string{"Ada.Strings.Text_Buffers", "Interfaces", "Wuffs.Runtime", targetPkg, basePkg, intsPkg, slicesPkg, endianPkg, ioPkg,
		rangesPkg, tokensPkg, utf8Pkg, formatsPkg, buffersPkg, swizzlerPkg}
	for _, o := range g.usedPackages() {
		candidates = append(candidates, o)
	}
	units, specUnits := []string(nil), []string(nil)
	for _, unit := range candidates {
		if specText != "" && needs(specText, unit) {
			specUnits = append(specUnits, unit)
		} else if needs(text, unit) {
			units = append(units, unit)
		}
	}
	// "with P.Q;" also makes P visible, and a body sees its spec's clauses.
	filtered := []string(nil)
	for _, u := range units {
		redundant := false
		for _, v := range append(append([]string(nil), units...), specUnits...) {
			redundant = redundant || strings.HasPrefix(v, u+".")
		}
		if !redundant {
			filtered = append(filtered, u)
		}
	}
	sort.Strings(filtered)
	b := strings.Builder{}
	for _, u := range filtered {
		b.WriteString("with " + u + ";\n")
	}
	if len(filtered) > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

func (g *gen) genSpec() string {
	p := &printer{}
	p.line("package " + g.adaPkgName + " with Preelaborate is")
	p.indent += indentStep

	for _, o := range g.sortedNamedTypes(true) {
		p.line("")
		p.declLine(o.decl)
	}
	for _, z := range g.statusList {
		if z.ast.Public() {
			p.line("")
			g.printStatus(p, z)
		}
	}
	if len(g.statusList) > 0 {
		p.line("")
		p.comment("The message of a status of this package (a public or a private one), as\n" +
			"the base library's Get_Message gives it for a base status: the C\n" +
			"string without its leading '@', '$' or '#', such as \"" + g.opts.PackageName + ": " +
			g.statusList[0].msg[1:] + "\".\n" +
			"Message_Length is zero for any other status.  Get_Message copies as much\n" +
			"of the message as fits to the start of Buffer, sets the rest of Buffer to\n" +
			"spaces and Length to the number of characters copied.")
		p.line("function Message_Length (S : Wuffs.Status) return Natural;")
		p.line("")
		p.line("procedure Get_Message (S : Wuffs.Status; Buffer : out String; Length : out Natural);")
	}
	for _, c := range g.constList {
		if c.ast.Public() {
			p.line("")
			g.printConst(p, c)
		}
	}

	for _, s := range g.structList {
		p.line("")
		p.comment("Wuffs: struct " + s.ast.QID().Str(g.tm))
		if len(s.interfaces) == 0 {
			p.line("type " + s.name + " is limited private;")
		} else {
			p.line("type " + s.name + " is limited new " + strings.Join(s.interfaces, " and ") + " with private;")
		}
		p.line("")
		p.comment("Must be called before any other subprogram: they do nothing (and return\n" +
			"zero or an error status) until it has been.")
		p.line("procedure Initialize (Self : in out " + s.name + ");")
		for _, fi := range g.funcList {
			if fi.recv == s && fi.ir.public {
				p.line("")
				p.comment("Wuffs: func " + fi.ir.wuffsName)
				p.fnSpec(fi.ir)
			}
		}
	}

	p.indent -= indentStep
	p.line("")
	p.line("private")
	p.indent += indentStep

	for _, o := range g.sortedNamedTypes(false) {
		p.line("")
		p.declLine(o.decl)
	}
	for _, z := range g.statusList {
		if !z.ast.Public() {
			p.line("")
			g.printStatus(p, z)
		}
	}

	for _, s := range g.structList {
		p.line("")
		if len(s.interfaces) == 0 {
			p.line("type " + s.name + " is limited record")
		} else {
			p.line("type " + s.name + " is limited new " + strings.Join(s.interfaces, " and ") + " with record")
		}
		p.indent += indentStep
		p.comment("Whether Initialize has been called (C: private_impl.magic).")
		p.line("Magic : Wuffs.U32 := 0;")
		if s.hasActiveCoroutine {
			p.comment("Which public coroutine is suspended, if any (C: active_coroutine).")
			p.line(activeCoroutineField + " : Wuffs.U32 := 0;")
		}
		for _, f := range append(append([]fieldInfo(nil), s.fields...), s.extra...) {
			switch {
			case f.typ.kind == kUtility:
				// An empty struct.
			case f.typ.kind == kStruct, f.typ.kind == kSwizzler:
				// These have default-initialized components of their own.
				p.line(f.name + " : " + f.typ.name + ";")
			case f.typ.zeroValue() != nil:
				p.line(f.name + " : " + f.typ.name + " := " + flat(f.typ.zeroValue()) + ";")
			default:
				// No default: an array aggregate could be materialized on
				// the stack. Initialize fills the array in place.
				p.line(f.name + " : " + f.typ.name + ";")
			}
		}
		p.indent -= indentStep
		if len(s.interfaces) == 0 {
			p.line("end record;")
		} else {
			// For a tagged type, Ada 2022 has the compiler write a
			// Put_Image procedure (for 'Image) that prints every component;
			// its stack frame grows with the record. Nothing uses it, so
			// replace it with one that does nothing.
			p.line("end record")
			p.line("with Put_Image => " + putImageName + ";")
			p.line("")
			p.comment("Not for use: it stands in for the procedure that the compiler would\n" +
				"otherwise generate for " + s.name + "'Image.")
			p.line("procedure " + putImageName)
			p.line("  (Buffer : in out Ada.Strings.Text_Buffers.Root_Buffer_Type'Class; Arg : " + s.name + ")")
			p.line("is null;")
		}
	}
	for _, fi := range g.funcList {
		if !fi.ir.public {
			p.line("")
			p.comment("Wuffs: func " + fi.ir.wuffsName)
			p.fnSpec(fi.ir)
		}
		if fi.dispatch != nil {
			p.line("")
			p.comment("Wuffs: func " + fi.dispatch.wuffsName)
			p.fnSpec(fi.dispatch)
		}
	}

	p.indent -= indentStep
	p.line("")
	p.line("end " + g.adaPkgName + ";")
	return p.b.String()
}

func (g *gen) genBody() string {
	// Print the subprograms first, as doing so does not change g.useType,
	// but be explicit about the order of evaluation.
	p := &printer{}
	p.line("package body " + g.adaPkgName + " is")
	p.indent += indentStep

	bits := []int(nil)
	for b, ok := range g.useType {
		if ok {
			bits = append(bits, b)
		}
	}
	sort.Ints(bits)
	if len(bits) > 0 {
		p.line("")
	}
	for _, b := range bits {
		p.line("use type " + numType(b).name + ";")
	}

	for _, c := range g.constList {
		// A private constant that only constant expressions mention has
		// been folded away, and GNAT warns about unreferenced entities.
		if !c.ast.Public() && c.used {
			p.line("")
			g.printConst(p, c)
		}
	}

	if len(g.statusList) > 0 {
		g.printMessages(p)
	}
	for _, s := range g.structList {
		p.line("")
		g.printInitialize(p, s)
	}
	for _, fi := range g.funcList {
		p.line("")
		p.fnBody(fi.ir)
		if fi.dispatch != nil {
			p.line("")
			p.fnBody(fi.dispatch)
		}
	}

	p.indent -= indentStep
	p.line("")
	p.line("end " + g.adaPkgName + ";")
	return p.b.String()
}

func (g *gen) printStatus(p *printer, z *statusInfo) {
	p.comment("Wuffs: status " + z.ast.QID()[1].Str(g.tm))
	decl := fmt.Sprintf("%s : constant Wuffs.Status :=", z.name)
	value := fmt.Sprintf("(%s, %s);", z.category, numLiteral(big.NewInt(int64(z.code)), 8))
	if p.indent+len(decl)+1+len(value) <= maxCol {
		p.line(decl + " " + value)
	} else {
		p.line(decl)
		p.line("  " + value)
	}
}

func (g *gen) printInitialize(p *printer, s *structInfo) {
	p.line("procedure Initialize (Self : in out " + s.name + ") is")
	p.line("begin")
	p.indent += indentStep
	if s.hasActiveCoroutine {
		p.line("Self." + activeCoroutineField + " := 0;")
	}
	for _, f := range append(append([]fieldInfo(nil), s.fields...), s.extra...) {
		switch f.typ.kind {
		case kUtility:
			// An empty struct.
		case kSwizzler:
			// An obligation from wuffs-base-pixel_swizzler.ads: the swizzler
			// must be the default (un-prepared) one, never raw memory.
			p.line("Self." + f.name + " := (others => <>);")
		case kStruct:
			// C: the sub-struct's initialize function.
			pkg := ""
			if f.typ.st.pkg != nil {
				pkg = f.typ.st.pkg.adaName + "."
			}
			p.line(pkg + "Initialize (Self." + f.name + ");")
		default:
			g.printZeroFill(p, "Self."+f.name, f.typ, 0)
		}
	}
	p.line("Self.Magic := Wuffs.Runtime.Magic_Initialized;")
	p.indent -= indentStep
	p.line("end Initialize;")
}

// printZeroFill assigns the zero value to the object called name, in place.
func (g *gen) printZeroFill(p *printer, name string, typ *adaType, depth int) {
	if typ.kind != kArray {
		p.line(name + " := " + flat(typ.zeroValue()) + ";")
		return
	}
	i := fmt.Sprintf("%sI%d", prefixGen, depth)
	p.line("for " + i + " in " + name + "'Range loop")
	p.indent += indentStep
	g.printZeroFill(p, name+" ("+i+")", typ.elem, depth+1)
	p.indent -= indentStep
	p.line("end loop;")
}

func (g *gen) printConst(p *printer, c *constInfo) {
	p.comment("Wuffs: const " + c.ast.QID().Str(g.tm))
	prefix := c.name + " : constant " + c.typ.name + " :="
	v := c.ast.Value()
	if c.typ.kind == kNum {
		p.line(prefix + " " + sourceLiteral(v.ConstValue(), "") + ";")
		return
	}
	p.line(prefix)
	lines := g.constAggregate(v, c.typ, p.indent+2)
	lines[len(lines)-1] += ";"
	p.rawLines(lines)
}

// constAggregate returns the lines of an array aggregate, the first of which
// is indented to col.
func (g *gen) constAggregate(v *a.Expr, typ *adaType, col int) []string {
	elems, _ := v.IsList()
	lines := []string(nil)
	if typ.elem.kind == kArray {
		for i, o := range elems {
			sub := g.constAggregate(o.AsExpr(), typ.elem, col+1)
			if i == 0 {
				sub[0] = spaces(col) + "[" + strings.TrimLeft(sub[0], " ")
			}
			if i == len(elems)-1 {
				sub[len(sub)-1] += "]"
			} else {
				sub[len(sub)-1] += ","
			}
			lines = append(lines, sub...)
		}
		return lines
	}

	hexDigits := typ.elem.bits / 4
	line := spaces(col) + "["
	for i, o := range elems {
		s := numLiteral(o.AsExpr().ConstValue(), hexDigits)
		if typ.elem.kind == kBool {
			s = "False"
			if o.AsExpr().ConstValue().Sign() != 0 {
				s = "True"
			}
		}
		if i != len(elems)-1 {
			s += ","
		} else {
			s += "]"
		}
		// Leave room for a trailing "," or ";".
		if len(line)+len(s)+2 > maxCol && strings.TrimSpace(line) != "" && strings.TrimSpace(line) != "[" {
			lines = append(lines, strings.TrimRight(line, " "))
			line = spaces(col + 1)
		}
		line += s + " "
	}
	return append(lines, strings.TrimRight(line, " "))
}

// declLine prints a type or subtype declaration, breaking it after its "is"
// if it is too long for one line.
func (p *printer) declLine(decl string) {
	if i := strings.Index(decl, " is "); p.indent+len(decl) > maxCol && i >= 0 {
		p.line(decl[:i+3])
		p.line("  " + decl[i+4:])
		return
	}
	p.line(decl)
}

// printMessages prints the bodies of Message_Length and Get_Message.
func (g *gen) printMessages(p *printer) {
	text := func(z *statusInfo) string {
		return g.opts.PackageName + ": " + strings.ReplaceAll(z.msg[1:], "\"", "\"\"")
	}
	chain := func(action func(z *statusInfo) stmt, otherwise stmt) {
		if err := checkCalls([]stmt{otherwise}); err != nil {
			panic("adagen: " + err.Error())
		}
		for i, z := range g.statusList {
			kw := "if"
			if i != 0 {
				kw = "elsif"
			}
			p.line(kw + " S = " + z.name + " then")
			p.indent += indentStep
			p.stmt(action(z))
			p.indent -= indentStep
		}
		p.line("else")
		p.indent += indentStep
		p.stmt(otherwise)
		p.indent -= indentStep
		p.line("end if;")
	}

	p.line("")
	p.line("function Message_Length (S : Wuffs.Status) return Natural is")
	p.line("begin")
	p.indent += indentStep
	chain(func(z *statusInfo) stmt {
		return sReturn{raw(fmt.Sprint(len(g.opts.PackageName) + 2 + len(z.msg) - 1))}
	}, sReturn{raw("0")})
	p.indent -= indentStep
	p.line("end Message_Length;")

	p.line("")
	p.line("procedure Get_Message (S : Wuffs.Status; Buffer : out String; Length : out Natural) is")
	p.line("begin")
	p.indent += indentStep
	copyMessage := func(literal string) stmt {
		return sCall{callNamed("Wuffs.Runtime.Copy_Message",
			"Text", raw(literal), "Buffer", raw("Buffer"), "Length", raw("Length"))}
	}
	chain(func(z *statusInfo) stmt {
		return copyMessage("\"" + text(z) + "\"")
	}, copyMessage("\"\""))
	p.indent -= indentStep
	p.line("end Get_Message;")
}

